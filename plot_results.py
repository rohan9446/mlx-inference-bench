"""
Plots for the M1 / MLX-LM inference baseline.

Data: Qwen3-0.6B bf16, mlx_lm.server --prompt-cache-size 1,
load generated by NVIDIA AIPerf. All values are p50 unless noted.

Usage:  python plot_results.py
Writes: fig_itl_vs_context.png, fig_prefill_rate.png, fig_concurrency.png
"""

import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter

plt.rcParams.update({
    "figure.dpi": 130,
    "savefig.dpi": 130,
    "savefig.bbox": "tight",
    "font.size": 11,
    "axes.grid": True,
    "grid.alpha": 0.3,
    "grid.linestyle": "--",
    "axes.spines.top": False,
    "axes.spines.right": False,
    "legend.framealpha": 0.9,
})

# ---------------------------------------------------------------- data

# ISL sweep, concurrency 1
isl = [128, 512, 2048, 8192]
ttft_ms = [269.28, 520.30, 2023.14, 12024.67]
itl_ms = [22.50, 23.33, 26.52, 41.60]
prefill_toks = [475.25, 984.04, 1012.28, 681.19]

# Concurrency sweep, ISL 512 / OSL 128
conc = [1, 2, 4, 8]
c_ttft_ms = [520.30, 979.03, 1787.34, 3400.50]
c_itl_ms = [23.33, 44.12, 48.24, 53.70]
c_out_toks = [36.56, 38.70, 53.35, 96.02]

pow2 = FuncFormatter(lambda v, _: f"{int(v):,}")


# ---------------------------------------------------------------- fig 1
# ITL vs context length

fig, ax = plt.subplots(figsize=(7.5, 4.6))

ax.plot(isl, itl_ms, marker="o", color="C0")

for x, y in zip(isl, itl_ms):
    ax.annotate(f"{y:.1f}", (x, y), textcoords="offset points",
                xytext=(0, 9), ha="center", fontsize=10)

ax.set_xscale("log", base=2)
ax.set_xticks(isl)
ax.xaxis.set_major_formatter(pow2)
ax.set_xlabel("Input sequence length (tokens)")
ax.set_ylabel("Inter-token latency, p50 (ms)")
ax.set_title("Decode latency vs. context length\n"
             "Qwen3-0.6B bf16, MLX-LM, M1 8GB, concurrency 1", fontsize=11)
ax.set_ylim(0, 48)

fig.savefig("fig_itl_vs_context.png")
plt.close(fig)


# ---------------------------------------------------------------- fig 2
# Effective prefill rate vs context length

fig, ax = plt.subplots(figsize=(7.5, 4.6))

ax.plot(isl, prefill_toks, marker="s", color="C1")

for x, y in zip(isl, prefill_toks):
    ax.annotate(f"{y:.0f}", (x, y), textcoords="offset points",
                xytext=(0, 9), ha="center", fontsize=10)

ax.set_xscale("log", base=2)
ax.set_xticks(isl)
ax.xaxis.set_major_formatter(pow2)
ax.set_xlabel("Input sequence length (tokens)")
ax.set_ylabel("Effective prefill rate, ISL / TTFT (tokens/s)")
ax.set_title("Effective prefill rate vs. context length\n"
             "Qwen3-0.6B bf16, MLX-LM, M1 8GB, concurrency 1", fontsize=11)
ax.set_ylim(0, 1150)

fig.savefig("fig_prefill_rate.png")
plt.close(fig)


# ---------------------------------------------------------------- fig 3
# Concurrency: latency indexed to c=1 (left), throughput (right)

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.4))

ttft_rel = [v / c_ttft_ms[0] for v in c_ttft_ms]
itl_rel = [v / c_itl_ms[0] for v in c_itl_ms]

ax1.plot(conc, ttft_rel, marker="o", color="C1", label="TTFT (prefill)")
ax1.plot(conc, itl_rel, marker="s", color="C0", label="ITL (decode)")
ax1.set_xscale("log", base=2)
ax1.set_xticks(conc)
ax1.xaxis.set_major_formatter(pow2)
ax1.set_xlabel("Concurrent requests")
ax1.set_ylabel("Latency relative to concurrency 1")
ax1.set_title("Latency scaling", fontsize=11)
ax1.set_ylim(0, 7.2)
ax1.legend()

ax2.plot(conc, c_out_toks, marker="^", color="C2")
ax2.set_xscale("log", base=2)
ax2.set_xticks(conc)
ax2.xaxis.set_major_formatter(pow2)
ax2.set_xlabel("Concurrent requests")
ax2.set_ylabel("Output throughput, all users (tokens/s)")
ax2.set_title("Throughput scaling", fontsize=11)
ax2.set_ylim(0, 110)

fig.suptitle("Concurrency sweep: Qwen3-0.6B bf16, MLX-LM, M1 8GB, ISL 512 / OSL 128",
             fontsize=11)
fig.tight_layout()
fig.savefig("fig_concurrency.png")
plt.close(fig)

print("wrote fig_itl_vs_context.png, fig_prefill_rate.png, fig_concurrency.png")
